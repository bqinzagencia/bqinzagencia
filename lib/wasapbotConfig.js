export function getConfigIndustria(industria) {
  const cfg = CONFIG_INDUSTRIA[industria] || CONFIG_INDUSTRIA.otro;
  // Las industrias con citas necesitan saber cuanto dura cada servicio
  // para que el bot pueda calcular disponibilidad real (sin solapar agendas).
  return { ...cfg, tieneDuracion: !!cfg.tieneCitas };
}

// ── Horario semanal ──────────────────────────────────────────────
// Estructura por defecto: cada dia tiene si esta abierto y sus franjas horarias.
// Una franja = { de:'08:00', a:'18:00' }. Puede haber varias franjas por dia
// (ej: jornada partida con descanso al mediodia).
export const DIAS_SEMANA = [
  { key: 'lunes',     label: 'Lunes'     },
  { key: 'martes',    label: 'Martes'    },
  { key: 'miercoles', label: 'Miércoles' },
  { key: 'jueves',    label: 'Jueves'    },
  { key: 'viernes',   label: 'Viernes'   },
  { key: 'sabado',    label: 'Sábado'    },
  { key: 'domingo',   label: 'Domingo'   },
];

export function horarioSemanalDefault() {
  const dia = () => ({ abierto: false, franjas: [{ de: '08:00', a: '18:00' }] });
  const obj = {};
  DIAS_SEMANA.forEach(d => {
    obj[d.key] = dia();
    // Lunes a viernes abiertos por defecto, fin de semana cerrado
    if (!['sabado','domingo'].includes(d.key)) obj[d.key].abierto = true;
  });
  return obj;
}

